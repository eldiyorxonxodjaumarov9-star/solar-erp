import assert from 'node:assert/strict';
import { attendanceDate, calculateAttendanceSalary, salaryRateOnDate } from '../src/workers/attendanceSalary.js';
const worker = {id: 'w1', salary: 5200000, workingDays: 26, salaryEffectiveDate: '2026-10-03', salaryHistory: [{salary:3900000, workingDays:26, effectiveDate:'2026-10-01'}]};
const a = {id:'a', ustaId:'w1', loginTime:'2026-10-01T04:00:00Z'};
const b = {id:'b', ustaId:'w1', loginTime:'2026-10-02T04:00:00Z'};
const duplicate = {...a, id:'c', projectId:'another', loginTime:'2026-10-01T08:00:00Z'};
assert.equal(calculateAttendanceSalary([a,b], [worker]).total, 300000);
const result = calculateAttendanceSalary([duplicate,b,a], [worker]);
assert.equal(result.total, 300000);
assert.equal(result.rows.get(duplicate).amount, 0);
assert.equal(salaryRateOnDate(worker, '2026-10-02').dailySalary, 150000);
assert.equal(salaryRateOnDate(worker, '2026-10-03').dailySalary, 200000);
assert.equal(salaryRateOnDate(worker, '2026-09-30'), null);
assert.equal(attendanceDate({loginTime:'2026-09-30T20:00:00Z'}), '2026-10-01');
const before = {...a, dateKey:'2026-09-30'};
assert.equal(calculateAttendanceSalary([before], [worker]).total, 0);
assert.equal(calculateAttendanceSalary([before], [worker]).rows.get(before).status, 'missing-rate');
assert.equal(calculateAttendanceSalary([a], []).rows.get(a).status, 'missing-rate');
assert.equal(calculateAttendanceSalary([{...a, loginTime:null}], [worker]).total, 0);
assert.equal(calculateAttendanceSalary([a, {...b, dateKey:'2026-10-01'}], [worker]).total, 150000);
assert.equal(calculateAttendanceSalary([duplicate,b], [worker]).total, 300000);
assert.equal(calculateAttendanceSalary([a, {...b, dateKey:'2026-10-03'}], [worker]).total, 350000);
console.log('PASS: 150000 x 2 = 300000; duplicates, Tashkent, rate history, missing rate, absence, edits/deletes');
