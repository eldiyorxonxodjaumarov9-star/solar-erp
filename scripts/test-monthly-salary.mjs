import assert from 'node:assert/strict';
import { monthlySalaryReport } from '../src/workers/monthlySalary.js';
const worker = {id:'w1',salary:3900000,workingDays:26,salaryEffectiveDate:'2026-10-01'};
const workers = [worker, {...worker,id:'w2'}];
const logs = Array.from({length:20}, (_,i) => ({id:String(i),ustaId:'w1',loginTime:`2026-10-${String(i+1).padStart(2,'0')}T04:00:00Z`}));
logs.push({...logs[0], id:'duplicate',projectId:'other'}, {id:'nov',ustaId:'w1',loginTime:'2026-11-01T04:00:00Z'}, {id:'sep',ustaId:'w1',loginTime:'2026-09-01T04:00:00Z'});
const admin = {role:'admin'};
let rows = monthlySalaryReport(logs,workers,'2026-10',admin);
assert.equal(rows.length,2);
assert.equal(rows[0].total,3000000);
assert.equal(rows[0].workedDays,20);
assert.equal(rows[0].missingDays,0);
assert.equal(rows[1].total,0);
assert.equal(monthlySalaryReport(logs,workers,'2026-11',admin)[0].total,150000);
assert.equal(monthlySalaryReport(logs,workers,'2026-09',admin)[0].missingDays,1);
assert.equal(monthlySalaryReport(logs,workers,'2026-10',{role:'usta',workerId:'w2'}).length,1);
assert.equal(monthlySalaryReport(logs,workers,'2026-10',{role:'usta',workerId:'w2'})[0].total,0);
assert.deepEqual(monthlySalaryReport(logs,workers,'2026-10',{role:'asisten'}),[]);
const changed = {...worker,salary:5200000,salaryEffectiveDate:'2026-10-11',salaryHistory:[{salary:3900000,workingDays:26,effectiveDate:'2026-10-01'}]};
assert.equal(monthlySalaryReport(logs,[changed],'2026-10',admin)[0].total,3500000);
const missing = {...worker,salaryEffectiveDate:'2026-10-03'};
rows=monthlySalaryReport(logs,[missing],'2026-10',admin);
assert.equal(rows[0].missingDays,2);
assert.equal(rows[0].total,2700000);
assert.equal(monthlySalaryReport([{ustaId:'w1',loginTime:'2026-09-30T20:00:00Z'}],[worker],'2026-10',admin)[0].total,150000);
assert.equal(monthlySalaryReport(logs.slice(1),[worker],'2026-10',admin)[0].total,3000000);
console.log('PASS: 20 x 150000 = 3000000; month isolation, duplicates, history, missing days, Tashkent, role scope');
